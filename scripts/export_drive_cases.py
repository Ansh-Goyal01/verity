"""Rebuild web/drive/cases.js: the engine answers the drive pages replay when the API is unreachable.

Every answer comes from the engine through FastAPI's test client (in-memory graph); nothing is typed by hand.
Rebuilt here, because they depend on the planner:
  * ``dispatch``: per demo vehicle and starting charge (40/62/70/85 %), the plan's graph ``why``; the full ``release``
    unless that charge is the vehicle's demo charge (web/js/snapshot.js already carries those); and, for a GO, the
    scripted trip ``events`` and 101 live updates (0..100 %) at the checkpoint.
  * ``practice``: the scripted voice report (CH-0006 broken) and the re-check of the V12 demo plan it triggers.
  * ``clips``: the audio cache index (data/audio_cache/manifest.json).
Carried over unchanged from the current file (they do not depend on the planner): ``checkpoint``, ``rides``,
``chargers``, ``ledger``. Run after scripts/build_audio_cache.py; then the Node frontend tests.
"""

from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")  # starlette's httpx deprecation notice is irrelevant here

from fastapi.testclient import TestClient  # noqa: E402

from api.main import app, get_voice_client  # noqa: E402
from api.service import BOOKING, FLEET_META, EngineService  # noqa: E402
from verity.paths import DATA_DIR  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
CASES = ROOT / "web" / "drive" / "cases.js"
PREFIX = "window.VerityCases="
HEADER = "/* Generated by scripts/export_drive_cases.py from the Verity engine. */\n"
SOCS = (40, 62, 70, 85)
READING_T = "2026-10-28T14:55:00+05:30"  # the reading time export_api_examples.py uses; the answer depends on km + SoC
BASE = {k: BOOKING[k] for k in ("departure_time", "passengers", "ac_on", "target_confidence")} | {
    "origin": {k: BOOKING["origin"][k] for k in ("lat", "lon")},
    "destination": {k: BOOKING["destination"][k] for k in ("lat", "lon")}}
RELEASE_KEYS = ("plan_id", "vehicle_id", "decision", "reason", "confidence_display", "arrival_soc", "stops",
                "alternates", "levers", "refusal_reason", "n_runs", "is_simulated", "speech")
FORECAST_KEYS = ("km_along_route", "arrival_soc", "bingo_soc_pct_here", "action", "divert_to", "message")
PRACTICE = {"charger_id": "CH-0006", "status": "broken", "consent": True, "channel": "driver_voice",
            "note": "voice report"}


def read_current() -> dict:
    text = CASES.read_text(encoding="utf-8")
    start = text.index(PREFIX) + len(PREFIX)
    return json.loads(text[start:].rstrip().rstrip(";"))


def dispatch_cases(c: TestClient, checkpoint: dict) -> dict:
    out: dict = {}
    for vid, (_, demo_soc, _) in FLEET_META.items():
        out[vid] = {}
        for soc in SOCS:
            rel = c.post("/api/dispatch", json={**BASE, "vehicle_id": vid, "start_soc_pct": soc}).json()
            why = c.get(f"/api/graph/why/{rel['plan_id']}").json()
            case: dict = {"why": {"backend": why["backend"], "edges": why["edges"]}}
            if soc != demo_soc:
                case["release"] = {k: rel[k] for k in RELEASE_KEYS if k in rel}
            if rel["decision"] == "GO":
                case["events"] = c.get(f"/api/demo/replay/{rel['plan_id']}").json()["events"]
                case["forecasts"] = [
                    {k: f[k] for k in FORECAST_KEYS} for f in (
                        c.post("/api/forecast/update", json={"plan_id": rel["plan_id"], "t": READING_T, "lat": checkpoint["lat"],
                                                             "lon": checkpoint["lon"], "soc_pct": pct}).json()
                        for pct in range(101))]
            out[vid][str(soc)] = case
    return out


def practice_case() -> dict:
    """A fresh service holding only the V12 demo plan, so the re-check is exactly the one the page shows."""
    svc = EngineService()
    try:
        svc.dispatch({**BASE, "vehicle_id": "V12", "start_soc_pct": FLEET_META["V12"][1]})
        report = svc.add_report(PRACTICE, is_simulated=True)
        changed = report["trust_before"]["p_works"] != report["trust_after"]["p_works"]
        plans, pending = svc.replan_after_report(PRACTICE["charger_id"], trust_changed=changed)
        return {"report": report, "plans_checked": len(plans), "plans_pending": pending, "replan_failed": False,
                "plans": plans, "is_simulated": True}
    finally:
        svc.close()


def clips() -> list[dict]:
    manifest = json.loads((DATA_DIR / "audio_cache" / "manifest.json").read_text(encoding="utf-8"))
    return [{k: e[k] for k in ("file", "language", "text", "source")} for e in manifest["entries"].values()]


def main() -> int:
    current = read_current()
    app.dependency_overrides[get_voice_client] = lambda: None  # never call Sarvam from this script
    with TestClient(app) as c:
        dispatch = dispatch_cases(c, current["checkpoint"])
    cases = {"checkpoint": current["checkpoint"], "dispatch": dispatch, "rides": current["rides"],
             "chargers": current["chargers"], "practice": practice_case(), "ledger": current["ledger"],
             "clips": clips()}
    CASES.write_text(HEADER + PREFIX + json.dumps(cases, ensure_ascii=False, separators=(",", ":")) + ";\n",
                     encoding="utf-8")
    summary = {v: {s: d["release"]["decision"] if "release" in d else "(snapshot)" for s, d in cases.items()}
               for v, cases in dispatch.items()}
    print(f"wrote {CASES.relative_to(ROOT)}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
