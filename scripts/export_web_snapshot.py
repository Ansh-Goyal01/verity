"""Wrap the one snapshot bundle (scripts/export_snapshot.py) as web/js/snapshot.js for the frontend.

The Mission Control page (web/index.html) opens straight from disk (file://), where the browser cannot fetch JSON
files. The bundle itself, and the rule that every value in it is copied from a saved file, live in
scripts/export_snapshot.py (results/snapshot.json); this script only writes the same bundle as a JS file.

Engine work never writes into web/, so ONLY the frontend owner runs this:
    uv run python scripts/export_snapshot.py        (refresh results/snapshot.json from the saved results)
    uv run python scripts/export_web_snapshot.py    (write web/js/snapshot.js from it)
"""

from __future__ import annotations

import json
from pathlib import Path

from export_snapshot import ROOT, build_snapshot

OUT = ROOT / "web" / "js" / "snapshot.js"


def render_js(snapshot: dict) -> str:
    body = json.dumps(snapshot, separators=(",", ":"), ensure_ascii=False)
    return ("/* Generated by scripts/export_web_snapshot.py from results/snapshot.json's bundle. Do not edit by hand. */\n"
            f"window.VERITY_SNAPSHOT={body};\n")


def main(out: Path = OUT) -> None:
    with out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_js(build_snapshot()))
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
