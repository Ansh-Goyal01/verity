"""Bundle saved engine outputs and experiment results into web/js/snapshot.js.

The Mission Control page (web/index.html) opens straight from disk (file://), where the browser
cannot fetch JSON files. This script copies the saved, script-generated artifacts into one JS file:

- docs/api_examples/*.json  -> real engine responses for the simulated demo scenario
- results/*_simulated.json  -> condensed experiment summaries (E1-E5), values copied unchanged
- results/run_all_summary.json -> the last full test/experiment run status

Nothing is computed or rounded here beyond selecting fields; every value comes from a saved file.
Run: uv run python scripts/export_web_snapshot.py   (stdlib only)
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "docs" / "api_examples"
RESULTS = ROOT / "results"
OUT = ROOT / "web" / "js" / "snapshot.js"
VEHICLES = ("V07", "V12", "V19")


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def e1_summary(raw: dict) -> dict:
    methods = {}
    for name, by_k in raw["methods"].items():
        rows = []
        for k, row in by_k.items():
            band90 = row.get("bands", {}).get("90", {})
            rows.append({
                "k": int(k),
                "mae_pp": row.get("mae_pp"),
                "coverage90": band90.get("coverage"),
                "covered90": band90.get("covered"),
                "n90": band90.get("n"),
                "wilson90": band90.get("wilson95"),
            })
        methods[name] = sorted(rows, key=lambda r: r["k"])
    return {
        "experiment": raw["experiment"],
        "is_simulated": raw["is_simulated"],
        "test_trips": raw.get("test_trips"),
        "vehicles": raw.get("vehicles"),
        "resamples": raw.get("resamples"),
        "methods": methods,
        "notes": raw.get("notes", []),
    }


def e2_summary(raw: dict) -> dict:
    keep = ("ece", "brier", "coverage_90_arrival_band", "mean_90_band_width_pp",
            "share_extreme_predictions", "when_forecast_ge_0.9", "bins")
    return {
        "experiment": raw["experiment"],
        "is_simulated": raw["is_simulated"],
        "trips": raw.get("trips"),
        "n_runs": raw.get("n_runs"),
        "methods": {m: {k: v for k, v in body.items() if k in keep} for m, body in raw["methods"].items()},
    }


def main() -> None:
    api = {
        "health": load(EXAMPLES / "health.json"),
        "scenario": load(EXAMPLES / "demo_scenario.json"),
        "dispatch": {v: load(EXAMPLES / f"dispatch_{v}.json") for v in VEHICLES},
        "replay": {v: load(EXAMPLES / f"replay_{v}.json") for v in VEHICLES},
        "chargers": load(EXAMPLES / "chargers.json"),
        "forecastUpdate": load(EXAMPLES / "forecast_update.json"),
    }
    e3 = load(RESULTS / "e3_reliability_planning_simulated.json")
    e4 = load(RESULTS / "e4_dispatch_vs_fixed_simulated.json")
    e5 = load(RESULTS / "e5_trust_recovery_simulated.json")
    results = {
        "e1": e1_summary(load(RESULTS / "e1_learning_curve_simulated.json")),
        "e2": e2_summary(load(RESULTS / "e2_calibration_simulated.json")),
        "e3": {k: e3[k] for k in ("experiment", "is_simulated", "trips_per_scenario", "scenarios", "notes")},
        "e4": {k: e4[k] for k in ("experiment", "is_simulated", "trips_per_scenario", "total_simulated_trips",
                                   "scenarios", "compute", "notes")},
        "e5": {k: e5[k] for k in ("experiment", "is_simulated", "worlds_per_scenario", "chargers_per_world",
                                   "scenarios") if k in e5},
        "run_all": load(RESULTS / "run_all_summary.json"),
    }
    snapshot = {
        "source": "Saved engine outputs (docs/api_examples) and experiment results (results/). "
                  "Generated by scripts/export_web_snapshot.py; values are copied, not edited.",
        "is_simulated": True,
        "api": api,
        "results": results,
    }
    body = json.dumps(snapshot, separators=(",", ":"), ensure_ascii=False)
    OUT.write_text(
        "/* Generated by scripts/export_web_snapshot.py. Do not edit by hand. */\n"
        f"window.VERITY_SNAPSHOT={body};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
