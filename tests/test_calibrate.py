"""Calibration: observation building, Laplace posterior behaviour, fleet pooling. DEV-style tiny data."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from verity.calibrate import (
    DEFAULT_RHO_REL,
    calibrate,
    central_band,
    pool_fleet,
    predict_delta_soc,
    predictive_samples,
)
from verity.sim import generate_dataset, load_manifest
from verity.trips import TripObservation, load_sim_observation
from verity.vehicles import N_THETA, get_prior, to_physical

PRIOR = get_prior("compact_esuv")


@pytest.fixture(scope="module")
def sim_obs(tmp_path_factory: pytest.TempPathFactory) -> tuple[list[TripObservation], dict]:
    root = tmp_path_factory.mktemp("cal")
    manifest = generate_dataset("c", 99, out_root=root, fleet=(("v-1", "compact_esuv", 0.85),), trips_per_vehicle=9)
    obs = [load_sim_observation("c", m["trip_id"], root) for m in manifest["trips"]]
    return obs, manifest


def test_observation_matches_the_logged_trip(sim_obs: tuple[list[TripObservation], dict]) -> None:
    obs, manifest = sim_obs
    for o, meta in zip(obs, manifest["trips"]):
        assert o.distance_km == pytest.approx(meta["distance_km"], rel=0.02)
        assert o.delta_soc_pct > 0
        assert np.all((o.window_weights >= 0) & (o.window_weights <= 1))
        assert o.window_weights.sum() > 0.95 * o.segments.n  # SoC readings span (almost) the whole trip
        assert o.mass_kg > PRIOR.base.curb_mass_kg  # occupants add mass
        assert 1.0 <= o.segments.surface.min() and o.segments.dt_s.min() > 0


def test_no_observations_returns_the_prior() -> None:
    post = calibrate(PRIOR.u_mean, PRIOR.u_cov, [], PRIOR.base, PRIOR.nominal_kwh)
    assert post.n_trips == 0
    np.testing.assert_allclose(post.mean_u, PRIOR.u_mean)
    np.testing.assert_allclose(post.cov_u, PRIOR.u_cov)


def test_calibration_reduces_error_and_uncertainty_versus_the_prior(sim_obs) -> None:
    obs, _ = sim_obs
    train, test = obs[:6], obs[6:]
    rng = np.random.default_rng(0)
    prior_post = calibrate(PRIOR.u_mean, PRIOR.u_cov, [], PRIOR.base, PRIOR.nominal_kwh)
    post = calibrate(PRIOR.u_mean, PRIOR.u_cov, train, PRIOR.base, PRIOR.nominal_kwh)

    def mae(p) -> float:
        return float(np.mean([abs(np.median(predictive_samples(p, o, rng)) - o.delta_soc_pct) for o in test]))

    def width(p) -> float:
        lo, hi = central_band(predictive_samples(p, test[0], rng, n=2000))
        return hi - lo

    assert mae(post) < mae(prior_post)
    assert width(post) < width(prior_post)
    # the posterior has moved: the aged battery (85 % health) shows up as a lower usable fraction
    assert to_physical(post.mean_u)["usable_frac"] < to_physical(PRIOR.u_mean)["usable_frac"]


def test_more_trips_give_a_tighter_predictive_band(sim_obs) -> None:
    obs, _ = sim_obs
    widths = []
    for n in (1, 3, 6):
        post = calibrate(PRIOR.u_mean, PRIOR.u_cov, obs[:n], PRIOR.base, PRIOR.nominal_kwh)
        lo, hi = central_band(predictive_samples(post, obs[8], np.random.default_rng(1), n=3000, add_noise=False))
        widths.append(hi - lo)
    assert widths[0] > widths[1] > widths[2] * 0.95


def test_calibration_recovers_a_known_parameter_without_model_discrepancy(sim_obs) -> None:
    """Self-consistency: data generated BY the planner model are explained almost exactly."""
    obs, _ = sim_obs
    u_true = PRIOR.u_mean + np.array([0.1, -0.1, 0.2, 0.2, -0.8, 0.1])
    fake = []
    for o in obs[:6]:
        y = float(predict_delta_soc(PRIOR.base, PRIOR.nominal_kwh, u_true, o)[0])
        soc = np.array([100.0, 100.0 - y])
        fake.append(TripObservation(**{**o.__dict__, "soc_pct": soc, "soc_t_s": o.soc_t_s[[0, -1]]}))
    post = calibrate(PRIOR.u_mean, PRIOR.u_cov, fake, PRIOR.base, PRIOR.nominal_kwh, rho_rel=0.01)
    held = obs[7]
    truth = float(predict_delta_soc(PRIOR.base, PRIOR.nominal_kwh, u_true, held)[0])
    est = float(predict_delta_soc(PRIOR.base, PRIOR.nominal_kwh, post.mean_u, held)[0])
    assert abs(est - truth) < 0.05 * truth


def test_posterior_covariance_is_symmetric_positive_definite(sim_obs) -> None:
    obs, _ = sim_obs
    post = calibrate(PRIOR.u_mean, PRIOR.u_cov, obs[:5], PRIOR.base, PRIOR.nominal_kwh)
    np.testing.assert_allclose(post.cov_u, post.cov_u.T, atol=1e-12)
    assert np.all(np.linalg.eigvalsh(post.cov_u) > 0)
    assert np.all(np.diag(post.cov_u) <= np.diag(PRIOR.u_cov) + 1e-9)  # data never inflate the variance


def test_pooling_needs_two_vehicles_and_keeps_unidentified_directions_at_the_prior() -> None:
    mean, cov = pool_fleet([], PRIOR.u_mean, PRIOR.u_cov)
    np.testing.assert_allclose(mean, PRIOR.u_mean)
    np.testing.assert_allclose(cov, PRIOR.u_cov)


def test_pooling_learns_a_shared_fleet_offset(tmp_path: Path) -> None:
    """Two aged vehicles -> the pooled prior's usable fraction moves down and its spread stays valid."""
    fleet = (("a-1", "compact_esuv", 0.80), ("a-2", "compact_esuv", 0.82), ("a-3", "compact_esuv", 0.84))
    manifest = generate_dataset("p", 5, out_root=tmp_path, fleet=fleet, trips_per_vehicle=4)
    posts = []
    for veh in manifest["vehicles"]:
        obs = [load_sim_observation("p", t, tmp_path) for t in veh["trip_ids"]]
        posts.append(calibrate(PRIOR.u_mean, PRIOR.u_cov, obs, PRIOR.base, PRIOR.nominal_kwh))
    mean, cov = pool_fleet(posts, PRIOR.u_mean, PRIOR.u_cov)
    assert to_physical(mean)["usable_frac"] < to_physical(PRIOR.u_mean)["usable_frac"]
    assert np.all(np.linalg.eigvalsh(cov) > 0)
    assert mean.shape == (N_THETA,) and DEFAULT_RHO_REL > 0
    assert load_manifest("p", tmp_path)["is_simulated"] is True
