"""E2: when the forecast says X %, do X % of trips arrive? (SIMULATED data)

New long trips are generated by the truth simulator (planner physics differs from truth by design:
gusts, driver variability, battery ageing, traffic, AC cycling). Each vehicle is calibrated on its
TRAINING-split trips only. For every new trip the same calibrated model forecasts the arrival SoC twice:

* shared      - trip-level factors sampled once per run (Verity)
* independent - every factor re-drawn independently per segment (same per-segment marginals)

The start SoC is chosen from the shared forecast's median plus a random offset so predicted
probabilities spread over 0..1; the outcome is "arrived with at least the reserve" in the truth run.
Output: a calibration (reliability) chart, expected calibration error (ECE), Brier score, and the
coverage of the 90 % arrival band. Planning constants were chosen on the DEV seed, not on 'main'.
"""

from __future__ import annotations

import argparse
import json
import time

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from verity.calibrate import DEFAULT_RHO_REL, calibrate  # noqa: E402
from verity.forecast import RESERVE_PCT, ForecastConfig, build_route, simulate_runs  # noqa: E402
from verity.paths import RESULTS_DIR  # noqa: E402
from verity.physics import total_mass_kg  # noqa: E402
from verity.sim import VehicleTruth, load_truth, planner_view, run_trip, sample_trip_spec  # noqa: E402
from verity.splits import load_eval_dataset  # noqa: E402
from verity.trips import load_sim_observation  # noqa: E402
from verity.vehicles import get_prior  # noqa: E402

DISTANCE_RANGE_KM = {"small_ecar": (40.0, 110.0), "compact_esuv": (60.0, 180.0), "e_scooter": (12.0, 40.0)}
OFFSET_RANGE_PP = (-10.0, 14.0)  # start SoC = reserve + forecast median use + offset
BINS = np.linspace(0.0, 1.0, 11)
METHODS = ("shared", "independent")
LABELS = {"shared": "Shared trip-level factors (Verity)", "independent": "Independent segments (strawman)"}


def _bin_table(p: np.ndarray, hit: np.ndarray) -> list[dict]:
    rows = []
    idx = np.clip(np.digitize(p, BINS[1:-1]), 0, len(BINS) - 2)
    for b in range(len(BINS) - 1):
        m = idx == b
        rows.append({"lo": float(BINS[b]), "hi": float(BINS[b + 1]), "n": int(m.sum()),
                     "mean_pred": round(float(p[m].mean()), 4) if m.any() else None,
                     "observed": round(float(hit[m].mean()), 4) if m.any() else None})
    return rows


def _metrics(p: np.ndarray, hit: np.ndarray, inband: np.ndarray, width: np.ndarray) -> dict:
    rows = _bin_table(p, hit)
    n = len(p)
    ece = sum(r["n"] / n * abs(r["mean_pred"] - r["observed"]) for r in rows if r["n"])
    high = p >= 0.9
    return {
        "ece": round(float(ece), 4), "brier": round(float(np.mean((p - hit) ** 2)), 4),
        "coverage_90_arrival_band": round(float(np.mean(inband)), 4),
        "mean_90_band_width_pp": round(float(np.mean(width)), 3),
        "share_extreme_predictions": round(float(np.mean((p <= 0.05) | (p >= 0.95))), 4),
        "when_forecast_ge_0.9": {"n": int(high.sum()),
                                 "mean_pred": round(float(p[high].mean()), 4) if high.any() else None,
                                 "observed_arrival_rate": round(float(hit[high].mean()), 4) if high.any() else None},
        "bins": rows,
    }


def run_e2(dataset: str = "main", trips_per_vehicle: int = 60, seed: int = 5000, rho_rel: float = DEFAULT_RHO_REL,
           n_runs: int = 2000) -> dict:
    t0 = time.time()
    manifest, split = load_eval_dataset(dataset)
    cfg = ForecastConfig(n_runs=n_runs)
    acc = {m: {"p": [], "hit": [], "inband": [], "width": []} for m in METHODS}
    bias: dict[str, list[float]] = {}
    forecast_ms: list[float] = []
    for vi, veh in enumerate(manifest["vehicles"]):
        vid, key = veh["vehicle_id"], veh["class_key"]
        prior = get_prior(key)
        vt = VehicleTruth(**load_truth(dataset, veh["trip_ids"][0])["vehicle"])
        train = [load_sim_observation(dataset, t) for t in split["vehicles"][vid]["train"]]
        post = calibrate(prior.u_mean, prior.u_cov, train, prior.base, prior.nominal_kwh, rho_rel)
        for k in range(trips_per_vehicle):
            rng = np.random.default_rng([seed, vi, k])
            spec = sample_trip_spec(rng, vt, 20 + k, distance_range_km=DISTANCE_RANGE_KM[key], start_soc_pct=100.0)
            run = run_trip(rng, vt, spec)
            used_true = float(100.0 - run.soc_true_pct[-1])
            view = planner_view(rng, spec, run)
            route = build_route(prior.vtype, view["distance_km"], np.array(view["block_end_m"]),
                                np.array(view["block_kind"]), view["elevation"], view["weather"], view["bearing_deg"])
            mass = total_mass_kg(prior.base.curb_mass_kg, view["passengers"], view["cargo_kg"])
            t1 = time.time()
            runs = {"shared": simulate_runs(post, route, mass_kg=mass, ac_on=view["ac_on"], rng=rng, cfg=cfg, shared=True)}
            forecast_ms.append(1000 * (time.time() - t1))
            runs["independent"] = simulate_runs(post, route, mass_kg=mass, ac_on=view["ac_on"], rng=rng, cfg=cfg,
                                                shared=False)
            median_used = float(np.median(runs["shared"].total_used))
            start = float(np.clip(RESERVE_PCT + median_used + rng.uniform(*OFFSET_RANGE_PP), 20.0, 100.0))
            arrival_true = start - used_true
            bias.setdefault(key, []).append((median_used - used_true) / max(used_true, 1e-9))
            for m in METHODS:
                a = runs[m].arrival_soc(start)
                lo, hi = np.quantile(a, [0.05, 0.95])
                acc[m]["p"].append(float(np.mean(a >= RESERVE_PCT)))
                acc[m]["hit"].append(float(arrival_true >= RESERVE_PCT))
                acc[m]["inband"].append(float(lo <= arrival_true <= hi))
                acc[m]["width"].append(float(hi - lo))
    methods = {m: _metrics(*(np.array(acc[m][f]) for f in ("p", "hit", "inband", "width"))) for m in METHODS}
    return {
        "experiment": "E2 calibration of arrival probability", "is_simulated": True, "dataset": dataset,
        "reserve_pct": RESERVE_PCT, "trips": len(acc["shared"]["p"]), "trips_per_vehicle": trips_per_vehicle,
        "seed": seed, "n_runs": n_runs, "methods": methods,
        "median_forecast_energy_error_rel_by_class": {c: round(float(np.mean(v)), 4) for c, v in bias.items()},
        "compute_ms_per_shared_forecast_mean": round(float(np.mean(forecast_ms)), 1),
        "runtime_s": round(time.time() - t0, 1),
        "notes": ["Truth trips come from verity.sim (SIMULATED); vehicles calibrated on training-split trips only.",
                  "Success = arrival SoC >= reserve in the truth run."],
    }


def plot(result: dict, path) -> None:
    fig, ax = plt.subplots(figsize=(6.2, 6.0))
    ax.plot([0, 1], [0, 1], color="grey", ls="--", lw=1, label="perfectly calibrated")
    for m, colour in zip(METHODS, ("tab:green", "tab:red")):
        rows = [r for r in result["methods"][m]["bins"] if r["n"]]
        ax.plot([r["mean_pred"] for r in rows], [r["observed"] for r in rows], color=colour, lw=1.2,
                label=f"{LABELS[m]}  ECE {result['methods'][m]['ece']:.3f}")
        ax.scatter([r["mean_pred"] for r in rows], [r["observed"] for r in rows], s=[8 + 3 * r["n"] for r in rows],
                   color=colour, alpha=0.6)
    ax.set(xlabel="predicted probability of arriving with the reserve", ylabel="share of trips that actually arrived",
           xlim=(-0.02, 1.02), ylim=(-0.02, 1.02), title="E2: calibration of arrival probability (simulated)")
    ax.legend(loc="upper left", fontsize=8)
    fig.text(0.5, 0.005, f"SIMULATED trips from verity.sim: {result['trips']} trips, dataset '{result['dataset']}'. "
             "Marker size = trips in bin.", ha="center", fontsize=7)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    fig.savefig(path, dpi=140)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="E2 calibration (simulated)")
    parser.add_argument("--dataset", default="main")
    parser.add_argument("--trips-per-vehicle", type=int, default=60)
    parser.add_argument("--replot", action="store_true")
    args = parser.parse_args()
    out = RESULTS_DIR if args.dataset == "main" else RESULTS_DIR / "dev"
    out.mkdir(parents=True, exist_ok=True)
    stem = "e2_calibration_simulated"
    if args.replot:
        plot(json.loads((out / f"{stem}.json").read_text(encoding="utf-8")), out / f"{stem}.png")
        return
    result = run_e2(args.dataset, args.trips_per_vehicle)
    (out / f"{stem}.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    plot(result, out / f"{stem}.png")
    print(f"E2 ({args.dataset}, SIMULATED) {result['trips']} trips, runtime {result['runtime_s']} s, "
          f"{result['compute_ms_per_shared_forecast_mean']} ms per forecast")
    for m in METHODS:
        r = result["methods"][m]
        print(f"{LABELS[m]:36s} ECE {r['ece']:.3f}  Brier {r['brier']:.3f}  90%-band coverage {r['coverage_90_arrival_band']:.2f}  "
              f"width {r['mean_90_band_width_pp']:.1f} pp  when>=0.9: {r['when_forecast_ge_0.9']}")
    print("median-forecast relative energy error by class:", result["median_forecast_energy_error_rel_by_class"])


if __name__ == "__main__":
    main()
