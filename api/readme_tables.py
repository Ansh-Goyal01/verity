"""The README's evidence and results tables (W5.1), generated from saved files so no number is typed by hand.

`render_tables(results_dir)` builds the markdown; `splice(readme_text, tables)` swaps it between the two marker
comments. `scripts/export_readme_tables.py` writes it and `tests/test_readme_tables.py` fails when the README is stale.
A missing result file produces a row that says so, never a guessed number.
"""

from __future__ import annotations

import json
from pathlib import Path

from .ledger import build_ledger

START = "<!-- readme-tables:start (generated by scripts/export_readme_tables.py; do not edit) -->"
END = "<!-- readme-tables:end -->"


def _read(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _count(value: int | None) -> str:
    return "n/a" if value is None else str(value)


def _pct(rate: float) -> str:
    return f"{100 * rate:.1f}%"


def _interval(pair: list[float]) -> str:
    return f"{_pct(pair[0])} to {_pct(pair[1])}"


def _words(status: str) -> str:
    return status.lower().replace("_", " ")


def _ledger_rows(results_dir: Path) -> list[str]:
    ledger = build_ledger(results_dir)
    real = ledger["real"]
    reports = real["charger_reports"]
    bmw = real["bmw_i3_held_out"]
    rows = [
        ("Indian trips, hand-collected from public sources", f"{_count(real['trips']['usable'])} usable of {_count(real['trips']['rows'])} rows"),
        ("Charger reports (corpus + app snapshots)", f"{_count(reports['corpus_evidence_usable'])} + {_count(reports['app_snapshot_usable'])}"),
        ("Open Charge Map check-ins", f"{_count(reports['ocm_checkins'])} ({_words(reports['ocm_status'])})"),
        ("App reviews, classified", f"{_count(real['app_reviews']['usable'])} usable of {_count(real['app_reviews']['rows'])}"),
        ("Voice notes from real speakers", f"{real['voice_notes']['count']} ({_words(real['voice_notes']['status'])})"),
    ]
    if bmw["status"] == "DONE":
        rows.append(("BMW i3 trips, held out, opened once (Germany, not India)", f"{bmw['trips_scored']} trips, {bmw['km_scored']:.0f} km"))
    else:
        rows.append(("BMW i3 held-out evaluation", _words(bmw["status"])))
    out = ["| Real evidence | Count |", "|---|---|"] + [f"| {name} | {count} |" for name, count in rows]
    sim = ledger["simulated"]["experiments"]
    out += ["", "| Simulated (every chart says so) | Trips or worlds per scenario |", "|---|---|"]
    out += [f"| {e['experiment']} | {_count(e['units']) if e['present'] else 'result file missing'} |" for e in sim]
    return out


def _result_rows(results_dir: Path) -> list[str]:
    rows: list[tuple[str, str, str, str]] = []  # what, data, n, outcome
    e4 = _read(results_dir / "e4_dispatch_vs_fixed_simulated.json")
    if e4:
        for name in ("0% chargers down", "20% chargers down", "40% chargers down"):
            s = e4["scenarios"].get(name)
            if s:
                rows.append((f"E4 stranded trips, {name}", "simulated", f"{s['trips']} trips",
                             f"fixed plan {_pct(s['stranding_rate_fixed'])} ({_interval(s['ci95_fixed'])}), "
                             f"dispatch {_pct(s['stranding_rate_dispatch'])} ({_interval(s['ci95_dispatch'])})"))
    e3 = _read(results_dir / "e3_reliability_planning_simulated.json")
    if e3:
        s = e3["scenarios"].get("40% chargers down")
        if s:
            rows.append(("E3 stranded trips, 40% chargers down", "simulated", f"{s['trips']} trips",
                         f"reliability-blind {_pct(s['stranding_rate_blind'])}, trust-aware {_pct(s['stranding_rate_trust_aware'])}"))
    e2 = _read(results_dir / "e2_calibration_simulated.json")
    if e2:
        shared, indep = e2["methods"]["shared"], e2["methods"]["independent"]
        rows.append(("E2 the 90% arrival band covers the outcome", "simulated", f"{e2['trips']} trips",
                     f"shared trip factors {_pct(shared['coverage_90_arrival_band'])}, "
                     f"independent segments {_pct(indep['coverage_90_arrival_band'])}"))
    bmw = _read(results_dir / "bmw_i3_heldout.json")
    if bmw:
        v2 = bmw["results"]["v2_frozen_prior"]
        cap, drop = v2["capacity"], v2["per_trip_soc_drop"]
        rows.append(("BMW i3 usable-capacity error", "REAL (Germany)", f"{bmw['n_trips_scored']} trips",
                     f"{cap['error_pct']:+.1f}%; truth inside the 95% interval: {'yes' if cap['truth_in_ci95'] else 'no'}, "
                     f"inside the 80% interval: {'yes' if cap['truth_in_ci80'] else 'no'}"))
        rows.append(("BMW i3 battery drop per trip", "REAL (Germany)", f"{bmw['n_trips_scored']} trips",
                     f"median error {drop['median_abs_error_pp']:.2f} points; the 95% band covers {_pct(drop['band95_coverage'])} of trips"))
    out = ["| Result | Data | n | Outcome |", "|---|---|---|---|"]
    out += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
    return out


def render_tables(results_dir: Path) -> str:
    return "\n".join([*_ledger_rows(results_dir), "", *_result_rows(results_dir)])


def splice(readme_text: str, tables: str) -> str:
    """Replace what sits between the markers; raise if a marker is missing so the README cannot silently go stale."""
    head, sep, rest = readme_text.partition(START)
    _, end_sep, tail = rest.partition(END)
    if not sep or not end_sep:
        raise ValueError("README.md has no readme-tables markers")
    return f"{head}{START}\n{tables}\n{END}{tail}"
